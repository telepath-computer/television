type IconName = keyof typeof ICONS;

function isIconName(value: string | null): value is IconName {
  return value !== null && Object.hasOwn(ICONS, value);
}

export class IconElement extends HTMLElement {
  static observedAttributes = ["name"];

  connectedCallback(): void {
    this.#renderGlyph();
  }

  attributeChangedCallback(): void {
    if (this.isConnected) this.#renderGlyph();
  }

  #renderGlyph(): void {
    const root = this.shadowRoot ?? this.attachShadow({ mode: "open" });
    root.adoptedStyleSheets = [iconSheet];
    this.replaceChildren();

    const name = this.getAttribute("name");
    root.innerHTML = isIconName(name) ? ICONS[name] : "";
  }
}

if (!customElements.get("tv-icon")) {
  customElements.define("tv-icon", IconElement);
}
